/**
 * A ContractClient double. Reads are answered from the `events` and `badges`
 * lists; writes return a fake hash. No method reaches a network. Read and
 * write failures can be injected one shot at a time so error-mapping paths are
 * exercised the way the real client throws.
 */
export function clientFactory(
  events: EventRecord[] = [],
  badges: BadgeRecord[] = [],
): ContractClient & {
  failNextReadWith: (error: unknown) => void;
  failNextWriteWith: (error: unknown) => void;
  /** Every `create_event` the page prepared, so tests can assert on the root. */
  preparedCreates: Parameters<ContractClient['prepareCreateEvent']>[0][];
  /** Every `claim` the page prepared, so tests can assert on the arguments. */
  preparedClaims: Parameters<ContractClient['prepareClaim']>[0][];
} {
  const eventById = new Map(events.map((event) => [event.id, event]));
  const preparedCreates: Parameters<ContractClient['prepareCreateEvent']>[0][] = [];
  const preparedClaims: Parameters<ContractClient['prepareClaim']>[0][] = [];
  let readFailure: unknown = null;
  let writeFailure: unknown = null;

  function throwRead(): void {
    if (readFailure !== null) {
      const error = readFailure;
      readFailure = null;
      throw error;
    }
  }

  const submit = async (): Promise<SubmitResult> => {
    if (writeFailure !== null) {
      const error = writeFailure;
      writeFailure = null;
      throw error;
    }
    return { hash: FAKE_HASH };
  };

  return {
    async getEvent(_source, eventId) {
      throwRead();
      const event = eventById.get(eventId);
      if (event === undefined) {
        throw new Error('HostError: Error(Contract, #1)');
      }
      return event;
    },
    async hasBadge(_source, eventId, attendee) {
      throwRead();
      return badges.some((badge) => badge.eventId === eventId && badge.attendee === attendee);
    },
    async badgesOf(_source, eventId, attendee) {
      throwRead();
      return badges.filter((badge) => badge.eventId === eventId && badge.attendee === attendee);
    },
    async prepareCreateEvent(input) {
      throwRead();
      preparedCreates.push(input);
      return { xdr: 'fake-xdr' };
    },
    async prepareClaim(input) {
      throwRead();
      preparedClaims.push(input);
      return { xdr: 'fake-xdr' };
    },
    async prepareAward() {
      throwRead();
      return { xdr: 'fake-xdr' };
    },
    async prepareRevoke() {
      throwRead();
      return { xdr: 'fake-xdr' };
    },
    submit,
    preparedCreates,
    preparedClaims,
    failNextReadWith(error: unknown) {
      readFailure = error;
    },
    failNextWriteWith(error: unknown) {
      writeFailure = error;
    },
  };
}

/** PageProps assembled from the doubles, ready to spread into a page. */
export function pagePropsFactory(
  options: {
    client?: ContractClient;
    config?: AppConfig;
    wallet?: WalletController;
  } = {},
): PageProps {
  return {
    client: options.client ?? clientFactory([]),
    config: options.config ?? configFactory(),
    wallet: options.wallet ?? walletFactory(),
  };
}
