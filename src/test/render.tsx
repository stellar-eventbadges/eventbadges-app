// RTL's auto-cleanup registers via the global afterEach, which vitest does not
// enable with globals: false, so run it here for every render test.
afterEach(() => {
  cleanup();
});

/**
 * Renders into happy-dom (act-safe, via RTL) and runs the axe-core
 * accessibility check, rejecting on serious or critical violations.
 */
export async function renderWithA11y(ui: ReactElement): Promise<RenderResult> {
  const result = render(ui);
  const results = await axe.run(result.container, {
    resultTypes: ['violations'],
    // Stylesheets are not loaded in the test DOM, so axe cannot compute real
    // contrast ratios here; contrast is covered by the design tokens, which
    // were measured by hand.
    rules: { 'color-contrast': { enabled: false } },
  });
  const serious = results.violations.filter(
    (v) => v.impact === 'serious' || v.impact === 'critical',
  );
  if (serious.length > 0) {
    throw new Error(
      `axe found ${serious.length} serious/critical violations: ` +
        serious
          .map((v) => `${v.id}: ${v.nodes.map((n) => n.target.join(' ')).join(', ')}`)
          .join('; '),
    );
  }
  return result;
}

/**
 * Renders and returns the queries, skipping the accessibility check — for
 * tests that assert something axe would legitimately flag elsewhere in the
 * fixture, or where the a11y check is covered by another test.
 */
export function renderOnly(ui: ReactElement): RenderResult {
  return render(ui);
}

/**
 * Queries text across the container, including inside hidden (sr-only) nodes.
 * happy-dom keeps clipped content in the DOM and in textContent, so the
 * sr-only additions are assertable here.
 */
export function textOf(container: HTMLElement): string {
  return container.textContent ?? '';
}

/**
 * A fake account address, generated by the real SDK so it passes the same
 * StrKey checksum validation the app applies. Random, never a real account,
 * and never derived from any personal data.
 */
export function fakeAccount(_seed = 0): string {
  return Keypair.random().publicKey();
}

/**
 * A fake contract id, encoded by the real SDK so it passes StrKey validation.
 * The seed fills the 32-byte payload deterministically; it is not a real
 * contract on any network.
 */
export function fakeContractId(seed = 0): string {
  return StrKey.encodeContract(new Uint8Array(32).fill(seed & 0xff));
}

const FAKE_HASH = 'a'.repeat(64);

