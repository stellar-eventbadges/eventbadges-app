describe('qrEncode known answers', () => {
  for (const vector of KNOWN_VECTORS) {
    it(`matches the reference for ${vector.name}`, () => {
      const qr = qrEncode(vector.payload, vector.level, {
        mask: vector.mask,
        version: vector.version,
      });
      expect(qr.size).toBe(vector.rows.length);
      expect(rows(qr)).toEqual(vector.rows);
    });
  }

  for (const vector of MASK_VECTORS) {
    it(`matches the reference for mask ${vector.mask} of the claim code`, () => {
      const qr = qrEncode(CLAIM_CODE, 'L', { mask: vector.mask, version: 4 });
      expect(qr.size).toBe(33);
      expect(rows(qr)).toEqual(vector.rows);
    });
  }
});

describe('qrEncode version selection', () => {
  it('uses version 1 for a short payload at level L', () => {
    expect(qrEncode('eventbadges', 'L').size).toBe(21);
  });

  it('uses version 4 for the 64-character claim code at level L', () => {
    // 64 bytes plus the mode and count bits need 93 data codewords, which is
    // version 4 (33x33) at L — the decision recorded in ADR 0004.
    expect(qrEncode(CLAIM_CODE, 'L').size).toBe(33);
  });

  it('uses a larger version at the higher correction levels', () => {
    expect(qrEncode(CLAIM_CODE, 'M').size).toBeGreaterThan(33);
    expect(qrEncode(CLAIM_CODE, 'H').size).toBeGreaterThanOrEqual(
      qrEncode(CLAIM_CODE, 'Q').size,
    );
  });

  it('is deterministic: the same input gives the same matrix', () => {
    expect(rows(qrEncode(CLAIM_CODE, 'L'))).toEqual(rows(qrEncode(CLAIM_CODE, 'L')));
  });

  it('rejects an out-of-range version and mask', () => {
    expect(() => qrEncode(CLAIM_CODE, 'L', { version: 0 })).toThrow(RangeError);
    expect(() => qrEncode(CLAIM_CODE, 'L', { version: 41 })).toThrow(RangeError);
    expect(() => qrEncode(CLAIM_CODE, 'L', { mask: 8 })).toThrow(RangeError);
  });
});

describe('qrEncode / qrDecode round-trip', () => {
  const cases: readonly { readonly label: string; readonly payload: string; readonly level: ErrorCorrectionLevel }[] = [
    { label: 'an empty payload', payload: '', level: 'L' },
    { label: 'a short ASCII payload', payload: 'eventbadges', level: 'M' },
    { label: 'the 64-character claim code', payload: CLAIM_CODE, level: 'L' },
    { label: 'the claim code at level H', payload: CLAIM_CODE, level: 'H' },
    { label: 'the claim code at level Q', payload: CLAIM_CODE, level: 'Q' },
    { label: 'a version 7 payload (version information is drawn)', payload: 'x'.repeat(150), level: 'L' },
    { label: 'a version 10 payload (16-bit length field)', payload: 'y'.repeat(250), level: 'L' },
    { label: 'a large high-correction payload', payload: 'z'.repeat(60), level: 'H' },
    { label: 'a payload with non-ASCII characters', payload: 'badge-\u00e9\u00e8', level: 'Q' },
  ];

  for (const testCase of cases) {
    it(`round-trips ${testCase.label}`, () => {
      const qr = qrEncode(testCase.payload, testCase.level);
      expect(qrDecode(qr)).toBe(testCase.payload);
    });
  }

  it('round-trips every mask pattern', () => {
    for (let mask = 0; mask < 8; mask += 1) {
      expect(qrDecode(qrEncode(CLAIM_CODE, 'L', { mask }))).toBe(CLAIM_CODE);
    }
  });

  it('round-trips all four correction levels', () => {
    const levels: readonly ErrorCorrectionLevel[] = ['L', 'M', 'Q', 'H'];
    for (const level of levels) {
      expect(qrDecode(qrEncode(CLAIM_CODE, level))).toBe(CLAIM_CODE);
    }
  });
});

describe('qrDecode repairs damaged matrices', () => {
  // Rows and columns 9..23 are pure data in versions 4 through 6: every
  // function pattern (finders, separators, timing, format, alignment, version
  // blocks) sits outside that band, so flips there land only in data codewords.
  function flipsInDataBand(count: number): (readonly [number, number])[] {
    const flips: (readonly [number, number])[] = [];
    for (let i = 0; i < count; i += 1) {
      flips.push([9 + (i % 15), 9 + ((i * 7) % 15)]);
    }
    return flips;
  }

  function withFlips(qr: QrMatrix, flips: readonly (readonly [number, number])[]): QrMatrix {
    const modules = qr.modules.map((row) => [...row]);
    for (const [x, y] of flips) modules[y][x] = !modules[y][x];
    return { size: qr.size, modules };
  }

  it('repairs wrong codewords up to the level L budget', () => {
    // Version 4 at L: one block, 20 check codewords, so 10 wrong codewords
    // are repairable — and 10 flipped modules can damage at most 10.
    const qr = qrEncode(CLAIM_CODE, 'L', { version: 4 });
    expect(qrDecode(withFlips(qr, flipsInDataBand(10)))).toBe(CLAIM_CODE);
  });

  it('repairs wrong codewords spread over several blocks', () => {
    // Version 6 at Q: four blocks of 24 check codewords (12 repairable
    // each); 8 flips can damage at most 8 in any one block.
    const qr = qrEncode(CLAIM_CODE, 'Q', { version: 6 });
    expect(qrDecode(withFlips(qr, flipsInDataBand(8)))).toBe(CLAIM_CODE);
  });

  it('matches the format information tolerantly', () => {
    // Three wrong format modules are the BCH(15,5) code's repair radius.
    const qr = qrEncode(CLAIM_CODE, 'L', { version: 4 });
    const damaged = withFlips(qr, [
      [8, 0],
      [8, 2],
      [7, 8],
    ]);
    expect(qrDecode(damaged)).toBe(CLAIM_CODE);
  });

  it('throws rather than guess when the damage is beyond the budget', () => {
    // Inverting the whole 15x15 data band flips 225 modules, which must land
    // in more codewords than any block can repair.
    const qr = qrEncode(CLAIM_CODE, 'L', { version: 4 });
    const flips: (readonly [number, number])[] = [];
    for (let y = 9; y <= 23; y += 1) {
      for (let x = 9; x <= 23; x += 1) flips.push([x, y]);
    }
    expect(() => qrDecode(withFlips(qr, flips))).toThrow();
  });
});

describe('qrDecode guards', () => {
  it('refuses a matrix that is not a valid size', () => {
    expect(() => qrDecode({ size: 22, modules: [] })).toThrow(RangeError);
  });
});

describe('QR constants', () => {
  it('requires the standard four-module quiet zone', () => {
    expect(QR_QUIET_ZONE).toBe(4);
  });
});
