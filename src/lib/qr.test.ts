// Tests for the hand-rolled QR encoder and its clean-matrix decoder (draft 01,
// `docs/issue-drafts/01-claim-code-as-qr.md`).
//
// The encoder is pinned against known-answer matrices from an independent
// implementation: Kazuhiko Arase's MIT-licensed `qrcode-generator` (Python),
// with the mask pattern forced so both sides commit to the same one. The
// tables and bit-level rules were cross-checked against Nayuki's MIT-licensed
// `QR-Code-generator` (TypeScript) while `qr.ts` was written, and the two
// agree on every value used. Neither library is a dependency here: they are
// test oracles only, used to generate the strings below.
