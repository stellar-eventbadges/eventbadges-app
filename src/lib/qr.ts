/**
 * A QR Code encoder and a clean-matrix decoder, written by hand so the app
 * needs no QR dependency (draft 01, `docs/issue-drafts/01-claim-code-as-qr.md`).
 *
 * Scope: the payload is the organizer's claim code — 64 ASCII hexadecimal
 * characters — so only **byte mode** is implemented, at all four error
 * correction levels. Versions 1..40 are supported (the smallest that fits is
 * chosen), which is every size the standard defines. Numeric, alphanumeric,
 * kanji and ECI segments are deliberately not implemented: nothing in this app
 * encodes them, and a v0 that does one thing correctly beats one that does
 * four things approximately.
 *
 * The decoder reads a module matrix — no camera image, no binarisation; that
 * half is `qrScan.ts` (draft 02). It matches tolerant format bits and repairs
 * wrong codewords up to the level's Reed–Solomon budget, so a matrix sampled
 * from a real frame can survive a wrong module or three. It exists so the
 * round-trip test can prove the encoder is a pure, invertible function
 * (draft 01's acceptance criterion), and as the decoding half of the camera
 * scanner.
 *
 * Everything is integer-only and dependency-free, following `badgeArt.ts` and
 * `badgeCsv.ts`: the output is a pure function of the payload and the level, so
 * two machines produce the same matrix, and no network request is involved.
 *
 * Reference for the tables and the bit-level rules: ISO/IEC 18004, as
 * implemented by two independent, MIT-licensed libraries (Nayuki's
 * `QR-Code-generator` and Kazuhiko Arase's `qrcode-generator`), which agree on
 * every value used here. The known-answer test in `qr.test.ts` pins the output
 * against matrices generated by the second of those while the first was read
 * as the specification's cross-check.
 */

export type ErrorCorrectionLevel = 'L' | 'M' | 'Q' | 'H';

/** The standard's required margin of light modules around the symbol. */
export const QR_QUIET_ZONE = 4;

export interface QrMatrix {
  /** Modules per side: `version * 4 + 17`. */
  readonly size: number;
  /** `modules[row][col]`; `true` is a dark module. No quiet zone is included. */
  readonly modules: readonly (readonly boolean[])[];
}

export interface QrOptions {
  /** Force mask pattern 0..7; by default the lowest-penalty mask is chosen. */
  readonly mask?: number;
  /** Force version 1..40; by default the smallest version that fits is used. */
  readonly version?: number;
}

/** Byte mode's mode indicator, `0100` (ISO/IEC 18004 Table 2). */
const MODE_BYTE = 0x4;

/** Table index for each level: L, M, Q, H, as the tables below are ordered. */
const ECC_ORDINAL: Record<ErrorCorrectionLevel, number> = { L: 0, M: 1, Q: 2, H: 3 };

/** The two format bits each level carries (NOT the same as the ordinal). */
const ECC_FORMAT_BITS: Record<ErrorCorrectionLevel, number> = { L: 1, M: 0, Q: 3, H: 2 };

/** Reverse of `ECC_FORMAT_BITS`, indexed by the 2-bit value. */
const ECC_FROM_FORMAT_BITS: readonly ErrorCorrectionLevel[] = ['M', 'L', 'H', 'Q'];

